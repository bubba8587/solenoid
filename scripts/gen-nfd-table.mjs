// Writes crates/solenoid-core/src/nfd_table.rs from this Node's String.prototype.normalize("NFD"), the
// decompositions UNACCENT reads on the Rust core ([[C130]] rustCore). Rerun after a Node (Unicode) upgrade.
import { writeFileSync } from "node:fs";

// The scripts accents live in. The Cyrillic range skips U+0483–0489, combining marks NFD would reorder.
const ranges = [[0x80, 0x24f], [0x300, 0x36f], [0x370, 0x3ff], [0x400, 0x482], [0x48a, 0x4ff], [0x1e00, 0x1fff]];
const rows = [];
for (const [a, b] of ranges) {
  for (let c = a; c <= b; c++) {
    const s = String.fromCodePoint(c);
    const d = s.normalize("NFD");
    if (d === s) continue;
    // UNACCENT drops U+0300–U+036F, so a tail of anything else would let mark order show.
    if ([...d.slice(1)].some((ch) => ch.codePointAt(0) < 0x300 || ch.codePointAt(0) > 0x36f)) throw new Error(`U+${c.toString(16)} decomposes past the marks`);
    rows.push([c, d]);
  }
}
const hex = (n) => `0x${n.toString(16)}`;
const esc = (s) => [...s].map((ch) => `\\u{${ch.codePointAt(0).toString(16)}}`).join("");
writeFileSync("crates/solenoid-core/src/nfd_table.rs", [
  "// [[C130]] rustCore",
  "//! Generated by `node scripts/gen-nfd-table.mjs` from Node's `normalize(\"NFD\")`: each code point in `NFD_RANGES`",
  "//! whose decomposition differs, sorted. Anything else past ASCII sends UNACCENT to the TS.",
  "",
  `pub const NFD_RANGES: [(u32, u32); ${ranges.length}] = [${ranges.map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(", ")}];`,
  "",
  `pub static NFD: [(u32, &str); ${rows.length}] = [`,
  ...rows.map(([c, d]) => `    (${hex(c)}, "${esc(d)}"),`),
  "];",
  "",
].join("\n"));
