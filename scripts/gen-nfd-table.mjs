// Writes crates/solenoid-core/src/nfd_table.rs from this Node's String.prototype.normalize("NFD"), the
// decompositions UNACCENT reads on the Rust core ([[C130]] rustCore). Rerun after a Node (Unicode) upgrade.
import { writeFileSync } from "node:fs";

const nfd = (s) => s.normalize("NFD");
const isHangul = (c) => c >= 0xac00 && c <= 0xd7a3;
const isSurrogate = (c) => c >= 0xd800 && c <= 0xdfff;

// Every code point NFD changes, Hangul syllables aside (the core splits those by arithmetic).
const keys = [];
const index = [0];
const chars = [];
for (let c = 0x80; c <= 0x10ffff; c++) {
  if (isSurrogate(c) || isHangul(c)) continue;
  const s = String.fromCodePoint(c);
  const d = nfd(s);
  if (d === s) continue;
  keys.push(c);
  for (const ch of d) chars.push(ch.codePointAt(0));
  index.push(chars.length);
}

// The non-starters, ranked as their combining classes order them. JavaScript doesn't expose the class, so it is read
// off the reordering: a mark moves ahead of U+0345 (class 240, the highest) iff its class is lower and not zero.
const marks = [0x345];
for (let c = 0x80; c <= 0x10ffff; c++) {
  if (isSurrogate(c) || isHangul(c) || c === 0x345) continue;
  const m = String.fromCodePoint(c);
  if (nfd(m) !== m) continue;
  if (nfd(`aͅ${m}`) === `a${m}ͅ`) marks.push(c);
}
const before = (a, b) => { const x = String.fromCodePoint(a), y = String.fromCodePoint(b); return nfd(`a${y}${x}`) === `a${x}${y}`; };
marks.sort((a, b) => (before(a, b) ? -1 : before(b, a) ? 1 : 0));
const rank = new Map();
let r = 0;
for (let i = 0; i < marks.length; i++) {
  if (i === 0 || before(marks[i - 1], marks[i])) r++;
  rank.set(marks[i], r);
}
const ranked = [...rank].sort(([a], [b]) => a - b);
if (r > 255) throw new Error("more combining classes than a u8 holds");

const hex = (n) => `0x${n.toString(16)}`;
const rows = (xs, per) => Array.from({ length: Math.ceil(xs.length / per) }, (_, i) => `    ${xs.slice(i * per, i * per + per).join(", ")},`);
writeFileSync("crates/solenoid-core/src/nfd_table.rs", [
  "// [[C130]] rustCore",
  "//! Generated by `node scripts/gen-nfd-table.mjs` from Node's `normalize(\"NFD\")` (Unicode " + process.versions.unicode + ").",
  "//! `NFD_KEYS` lists each code point past ASCII whose full decomposition differs (Hangul syllables aside), sorted;",
  "//! key i decomposes to `NFD_CHARS[NFD_INDEX[i]..NFD_INDEX[i + 1]]`. `CCC` ranks the non-starters in the order",
  "//! their canonical combining classes sort them.",
  "",
  `pub static NFD_KEYS: [u32; ${keys.length}] = [`,
  ...rows(keys.map(hex), 12),
  "];",
  "",
  `pub static NFD_INDEX: [u16; ${index.length}] = [`,
  ...rows(index.map(String), 16),
  "];",
  "",
  `pub static NFD_CHARS: [u32; ${chars.length}] = [`,
  ...rows(chars.map(hex), 12),
  "];",
  "",
  `pub static CCC_KEYS: [u32; ${ranked.length}] = [`,
  ...rows(ranked.map(([c]) => hex(c)), 12),
  "];",
  "",
  `pub static CCC_RANKS: [u8; ${ranked.length}] = [`,
  ...rows(ranked.map(([, k]) => String(k)), 24),
  "];",
  "",
].join("\n"));
console.log(`${keys.length} decompositions, ${chars.length} chars, ${ranked.length} non-starters in ${r} classes`);
