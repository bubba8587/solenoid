// [[C130]] rustCore, [[C25]] firstClassUnits
// Writes crates/solenoid-core/src/convert_units.rs: CONVERT's unit table (src/graph/nodes/convertUnits.ts) as each
// unit's Excel code, dimension, SI scale and offset, read from the TS so the two stay one table.
import { writeFileSync } from "node:fs";
import { build } from "esbuild";

const out = await build({
  entryPoints: [new URL("../src/graph/nodes/convertUnits.ts", import.meta.url).pathname],
  bundle: true, format: "esm", write: false, platform: "neutral", logLevel: "silent",
});
const mod = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString("base64")}`);
const defs = mod.CONVERT_UNIT_DEFS;

/** A JS number as a Rust f64 literal that parses back to the same bits. */
const lit = (x) => {
  const s = String(x);
  return /[.e]/.test(s) ? s.replace("e+", "e") : `${s}.0`;
};
const dimKey = (dim) => Object.keys(dim).filter((k) => dim[k] !== 0).sort().map((k) => `${k}${dim[k]}`).join(" ");
const rows = Object.entries(defs).map(([key, d]) => {
  const offset = d.dim.offset === undefined ? "None" : `Some(${lit(d.dim.offset)})`;
  return `    (${JSON.stringify(key)}, ${JSON.stringify(d.excelCode)}, ${JSON.stringify(dimKey(d.dim.dim))}, ${lit(d.dim.scale)}, ${offset}),`;
});

writeFileSync(new URL("../crates/solenoid-core/src/convert_units.rs", import.meta.url), `// [[C130]] rustCore, [[D99]] rustIsSpec, [[C25]] firstClassUnits
//! CONVERT's units (\`src/graph/nodes/convertUnits.ts\`) and \`convert\` (\`src/graph/dimension.ts\`). Generated by
//! \`node scripts/gen-convert-units.mjs\`; rerun it when the TS table moves.

/// Each unit's key, its Excel code, its dimension (the nonzero exponents, sorted), its SI scale and its offset.
pub(crate) const UNITS: [(&str, &str, &str, f64, Option<f64>); ${rows.length}] = [
${rows.join("\n")}
];

/// The CONVERT formula's unit argument, an Excel code (\`"oz"\` is the fluid ounce), or else a key.
pub fn convert_unit_key(code: &str) -> Option<&'static str> {
    UNITS.iter().rev().find(|u| u.1 == code).or_else(|| UNITS.iter().find(|u| u.0 == code)).map(|u| u.0)
}

/// None for a key the table lacks, for units of different dimensions, or for a non-finite answer.
pub fn convert_value(x: f64, from_key: &str, to_key: &str) -> Option<f64> {
    let unit = |k: &str| UNITS.iter().find(|u| u.0 == k);
    let (from, to) = (unit(from_key)?, unit(to_key)?);
    if from.2 != to.2 {
        return None;
    }
    let base = x * from.3 + from.4.unwrap_or(0.0);
    let out = (base - to.4.unwrap_or(0.0)) / to.3;
    out.is_finite().then_some(out)
}
`);
