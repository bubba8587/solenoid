#!/usr/bin/env python3
"""Write src/graph/textWidths.gen.ts: glyph advances and kerning of the shipped Atkinson fonts.

The app draws its text in the Atkinson Hyperlegible fonts it bundles (@fontsource-variable), so a string's width is
fixed by the font files. This reads them, instances the variable sans at the weights the figures use, and keeps the
advances and kerning pairs of the characters a label is likely to hold. Rerun after a font upgrade:

    pip install fonttools brotli
    python3 scripts/gen-text-widths.py
"""
import json
import os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SANS = os.path.join(ROOT, "node_modules/@fontsource-variable/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-wght-normal.woff2")
MONO = os.path.join(ROOT, "node_modules/@fontsource-variable/atkinson-hyperlegible-mono/files/atkinson-hyperlegible-mono-latin-wght-normal.woff2")
OUT = os.path.join(ROOT, "src/graph/textWidths.gen.ts")
WEIGHTS = [400, 500, 600, 700]
# Kerning moves a 9 px label by well under a pixel a pair, so it is kept for ASCII at the ends of the weight range only.
KERN_WEIGHTS = [400, 700]
CHARS = "".join(chr(c) for c in range(32, 127)) + "".join(chr(c) for c in range(0xA0, 0x100)) + "–—‘’“”…•·×−€£°"


def pair_kerning(font, glyph_of):
    """Every kerning pair among CHARS, from the GPOS kern feature (pair adjustment, formats 1 and 2)."""
    wanted = {g: c for c, g in glyph_of.items() if ord(c) < 127}
    gpos = font["GPOS"].table
    lookups = set()
    for rec in gpos.FeatureList.FeatureRecord:
        if rec.FeatureTag == "kern":
            lookups.update(rec.Feature.LookupListIndex)
    out = {}
    for li in sorted(lookups):
        lookup = gpos.LookupList.Lookup[li]
        for sub in lookup.SubTable:
            if lookup.LookupType == 9:
                sub = sub.ExtSubTable
            if getattr(sub, "LookupType", 2) != 2:
                continue
            firsts = [g for g in sub.Coverage.glyphs if g in wanted]
            if sub.Format == 1:
                for g1 in firsts:
                    pset = sub.PairSet[sub.Coverage.glyphs.index(g1)]
                    for pv in pset.PairValueRecord:
                        v = getattr(pv.Value1, "XAdvance", 0) or 0
                        if v and pv.SecondGlyph in wanted:
                            out.setdefault((wanted[g1], wanted[pv.SecondGlyph]), v)
            else:
                c1 = sub.ClassDef1.classDefs
                c2 = sub.ClassDef2.classDefs
                seconds = [g for g in wanted]
                for g1 in firsts:
                    row = sub.Class1Record[c1.get(g1, 0)]
                    for g2 in seconds:
                        v = getattr(row.Class2Record[c2.get(g2, 0)].Value1, "XAdvance", 0) or 0
                        if v:
                            out.setdefault((wanted[g1], wanted[g2]), v)
    return out


def face(path, weight):
    font = TTFont(path)
    if "fvar" in font:
        font = instantiateVariableFont(font, {"wght": weight})
    cmap = font.getBestCmap()
    glyph_of = {c: cmap[ord(c)] for c in CHARS if ord(c) in cmap}
    adv = [font["hmtx"].metrics[glyph_of[c]][0] if c in glyph_of else -1 for c in CHARS]
    kern = pair_kerning(font, glyph_of) if "GPOS" in font else {}
    return font["head"].unitsPerEm, adv, kern


def main():
    sans = {}
    for w in WEIGHTS:
        upm, adv, kern = face(SANS, w)
        flat = []
        for (a, b), v in sorted(kern.items(), key=lambda kv: (CHARS.index(kv[0][0]), CHARS.index(kv[0][1]))):
            flat += [CHARS.index(a) * len(CHARS) + CHARS.index(b), v]
        sans[w] = {"adv": adv, "kern": flat if w in KERN_WEIGHTS else []}
    mono_upm, mono_adv, _ = face(MONO, 400)
    mono = max(a for a in mono_adv if a > 0)
    assert upm == 1000 and mono_upm == 1000
    versions = {}
    for pkg in ["atkinson-hyperlegible-next", "atkinson-hyperlegible-mono"]:
        with open(os.path.join(ROOT, f"node_modules/@fontsource-variable/{pkg}/package.json")) as fh:
            versions[f"@fontsource-variable/{pkg}"] = json.load(fh)["version"]
    lines = [
        "// [[C100]] chartIsAValue",
        "// Generated by scripts/gen-text-widths.py from the bundled Atkinson Hyperlegible fonts; do not edit.",
        "// Units are 1/1000 em. A missing glyph is -1.",
        "/** The font packages these were read from; textWidth.test.ts fails when an upgrade leaves the table behind. */",
        f"export const FONT_VERSIONS: Record<string, string> = {json.dumps(versions)};",
        f"export const TEXT_CHARS = {json.dumps(CHARS, ensure_ascii=False)};",
        f"export const SANS_WEIGHTS = {json.dumps(WEIGHTS)} as const;",
        "export const SANS_ADVANCE: readonly (readonly number[])[] = [",
        *[f"  {json.dumps(sans[w]['adv'], separators=(',', ':'))}," for w in WEIGHTS],
        "];",
        f"export const KERN_WEIGHTS = {json.dumps(KERN_WEIGHTS)} as const;",
        "/** ASCII kerning pairs at KERN_WEIGHTS, flattened as (left index × TEXT_CHARS.length + right index, adjustment). */",
        "export const SANS_KERN: readonly (readonly number[])[] = [",
        *[f"  {json.dumps(sans[w]['kern'], separators=(',', ':'))}," for w in KERN_WEIGHTS],
        "];",
        f"export const MONO_ADVANCE = {mono};",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {OUT}: {len(CHARS)} chars, kerning pairs {[len(sans[w]['kern']) // 2 for w in KERN_WEIGHTS]}, mono {mono}")


if __name__ == "__main__":
    main()
