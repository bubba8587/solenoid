// [[C130]] rustCore
// Writes crates/solenoid-core/src/letters.rs: JS `/\p{L}/u` as code-point ranges, from this Node's Unicode tables.
import { writeFileSync } from "node:fs";

const re = /\p{L}/u;
const ranges = [];
let start = -1;
for (let c = 0x80; c <= 0x110000; c++) {
  const ok = c < 0x110000 && !(c >= 0xd800 && c <= 0xdfff) && re.test(String.fromCodePoint(c));
  if (ok && start < 0) start = c;
  if (!ok && start >= 0) { ranges.push([start, c - 1]); start = -1; }
}
const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const lines = [];
let cur = "   ";
for (const [a, b] of ranges) {
  const x = ` (${hex(a)}, ${hex(b)}),`;
  if ((cur + x).length > 118) { lines.push(cur); cur = "   "; }
  cur += x;
}
lines.push(cur);
writeFileSync(new URL("../crates/solenoid-core/src/letters.rs", import.meta.url), `// [[C130]] rustCore
//! JS \`/\\p{L}/u\`: the Letter ranges above ASCII, from Unicode ${process.versions.unicode}. Generated by
//! \`node scripts/gen-letters.mjs\`; rerun it when the Node or browser Unicode version moves.

use std::cmp::Ordering;

pub fn is_letter(c: char) -> bool {
    let c = c as u32;
    if c < 0x80 {
        return (c as u8).is_ascii_alphabetic();
    }
    LETTERS
        .binary_search_by(|&(lo, hi)| if hi < c { Ordering::Less } else if lo > c { Ordering::Greater } else { Ordering::Equal })
        .is_ok()
}

const LETTERS: [(u32, u32); ${ranges.length}] = [
${lines.join("\n")}
];
`);
console.log(`${ranges.length} ranges, Unicode ${process.versions.unicode}`);
