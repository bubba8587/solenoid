// Writes public/third-party-licenses-rust.txt: every Rust crate compiled into the shipped wasm (crates/solenoid-graph,
// which links the core and the scheduler) and the desktop shell (src-tauri), with its license text, beside the npm
// inventory `rollup-plugin-license` writes. Needs `cargo install cargo-about --features cli`.
//   node scripts/rust-licenses.mjs           write it
//   node scripts/rust-licenses.mjs --check   exit 1 when the committed file is stale (CI)
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const DIR = path.join(ROOT, "scripts/rust-licenses");
const OUT = path.join(ROOT, "public/third-party-licenses-rust.txt");
const MANIFESTS = [["The engine (WebAssembly, web and desktop)", "crates/solenoid-graph/Cargo.toml"], ["The desktop shell", "src-tauri/Cargo.toml"]];

const parts = MANIFESTS.map(([title, manifest]) => {
  const body = execFileSync("cargo", ["about", "generate", "--config", path.join(DIR, "about.toml"), "--manifest-path", path.join(ROOT, manifest), path.join(DIR, "about.hbs")],
    { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 << 20 });
  return `################################################################################\n# ${title}: ${manifest}\n################################################################################\n${body.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&")}`;
});
const text = `Third-party Rust crates in Solenoid, with their licenses. Generated by scripts/rust-licenses.mjs.\n\n${parts.join("\n")}`;

if (process.argv.includes("--check")) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (now !== text) { console.error("public/third-party-licenses-rust.txt is stale: run node scripts/rust-licenses.mjs"); process.exit(1); }
  console.log("Rust license inventory is current");
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(text.length / 1024).toFixed(0)} KB)`);
}
