let _section: Map<string, ExcelSection> | null = null;

/** The Excel section a function sits in, by name; null for a name not filed (the coverage test fails on one). */
export function excelSection(name: string): ExcelSection | null {
  if (!_section) {
    _section = new Map();
    for (const s of EXCEL_SECTIONS) for (const n of BY_SECTION[s].split(/\s+/)) if (n) _section.set(n, s);
  }
  return _section.get(name.toUpperCase()) ?? null;
}
